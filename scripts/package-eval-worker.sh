#!/usr/bin/env bash
#
# Assembles the cloud eval worker's AgentCore CodeZip artifact.
#
# AgentCore's direct code deployment runs a Python zip that must already
# contain every dependency -- nothing is installed for you at deploy time, and
# the runtime is arm64 only. So this builds a staging tree of
# aarch64-manylinux wheels, drops the `promptatron` package next to them, adds
# the root-level entry module AgentCore executes, and zips it under a
# content-hashed key.
#
# The key is content-hashed on purpose. AgentCore reads the zip when the
# runtime is created or updated, and CloudFormation only rolls the runtime when
# a property it can see changes -- so a static S3 key means CFN sees no change
# and the old bundle keeps serving forever. A hash-versioned key makes every
# real code change a visible property change. (This is rsc-core's
# AgentArtifactKey lesson, applied to Python.)
#
# Usage:
#   scripts/package-eval-worker.sh              # build into .build/eval-worker
#   EVAL_WORKER_BUILD_DIR=/tmp/x scripts/...    # build somewhere else
#
# Writes <build-dir>/artifact.env with ARTIFACT_ZIP / ARTIFACT_SHA /
# ARTIFACT_KEY for `make deploy-worker` to source. Makes no AWS calls.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVER="${ROOT}/server"
BUILD_DIR="${EVAL_WORKER_BUILD_DIR:-${ROOT}/.build/eval-worker}"
STAGING="${BUILD_DIR}/staging"

# Must match the template's `Runtime: PYTHON_3_12`. AgentCore's managed runtimes
# are arm64 only, so the wheels are resolved for that platform regardless of
# what this build machine is.
PYTHON_VERSION="3.12"
PYTHON_PLATFORM="${EVAL_WORKER_PYTHON_PLATFORM:-aarch64-manylinux_2_28}"

log() { printf '\033[1m==>\033[0m %s\n' "$*" >&2; }

command -v uv >/dev/null || { echo "package-eval-worker: uv is required" >&2; exit 1; }
command -v zip >/dev/null || { echo "package-eval-worker: zip is required" >&2; exit 1; }

rm -rf "${STAGING}"
mkdir -p "${STAGING}" "${BUILD_DIR}"

# 1. Pin the dependency set from the server's lockfile, including the `worker`
#    extra (bedrock-agentcore). `--no-emit-project` leaves `promptatron` itself
#    out: it is pure Python and gets copied in below, so there is no wheel build
#    to cross-compile.
log "Exporting locked dependencies (worker extra)"
uv export \
  --project "${SERVER}" \
  --frozen \
  --no-dev \
  --extra worker \
  --no-emit-project \
  --no-hashes \
  --format requirements-txt \
  > "${BUILD_DIR}/requirements.txt"

# 2. Install them for the runtime's platform. `--only-binary=:all:` is the
#    safety net: a source distribution would be built for *this* machine's
#    architecture and fail at import inside the arm64 runtime, so the build
#    fails loudly here instead.
log "Installing wheels for ${PYTHON_PLATFORM} (py${PYTHON_VERSION})"
uv pip install \
  --python-platform "${PYTHON_PLATFORM}" \
  --python-version "${PYTHON_VERSION}" \
  --target "${STAGING}" \
  --only-binary=:all: \
  --no-installer-metadata \
  --requirement "${BUILD_DIR}/requirements.txt"

# 3. The application itself.
log "Staging the promptatron package"
cp -R "${SERVER}/promptatron" "${STAGING}/promptatron"

# 4. The entry module. AgentCore's CodeConfiguration.EntryPoint names a file at
#    the zip root, and it is executed rather than imported -- so the shim has to
#    start the server itself. Everything real lives in the package.
cat > "${STAGING}/agentcore_app.py" <<'PY'
"""AgentCore CodeZip entry point -- generated by scripts/package-eval-worker.sh.

`AgentRuntimeArtifact.CodeConfiguration.EntryPoint` names a file at the root of
the zip, so this shim exists purely to be that file. The worker itself is
`promptatron.worker.agentcore_app`; this re-exports its `app` (for a host that
imports the module and looks for one) and runs it (for a host that executes the
file as a script). Edit the package, not this.
"""

from promptatron.worker.agentcore_app import app

if __name__ == "__main__":
    app.run()
PY

# 5. Strip build noise so the hash reflects source, not incidental state.
find "${STAGING}" -type d -name '__pycache__' -prune -exec rm -rf {} + 2>/dev/null || true
find "${STAGING}" -type f -name '*.pyc' -delete
find "${STAGING}" -type d -name 'tests' -path '*/site-packages/*' -prune -exec rm -rf {} + 2>/dev/null || true

# 6. Zip deterministically enough that an unchanged tree hashes the same:
#    sorted entries, no extra attributes, timestamps normalised.
log "Zipping"
STAGED_ZIP="${BUILD_DIR}/eval-worker.zip"
rm -f "${STAGED_ZIP}"
find "${STAGING}" -exec touch -t 198001010000 {} + 2>/dev/null || true
( cd "${STAGING}" && find . -type f -o -type l | LC_ALL=C sort | zip -qX "${STAGED_ZIP}" -@ )

ARTIFACT_SHA="$(sha256sum "${STAGED_ZIP}" | cut -c1-16)"
ARTIFACT_KEY="eval-worker/${ARTIFACT_SHA}.zip"
ARTIFACT_ZIP="${BUILD_DIR}/${ARTIFACT_SHA}.zip"
mv -f "${STAGED_ZIP}" "${ARTIFACT_ZIP}"

cat > "${BUILD_DIR}/artifact.env" <<ENV
ARTIFACT_ZIP=${ARTIFACT_ZIP}
ARTIFACT_SHA=${ARTIFACT_SHA}
ARTIFACT_KEY=${ARTIFACT_KEY}
ENV

log "Artifact: ${ARTIFACT_ZIP} ($(du -h "${ARTIFACT_ZIP}" | cut -f1))"
log "S3 key:   ${ARTIFACT_KEY}"
